/* Live end-to-end check of the round-clock rules against the running server.
   The signer comes from eth_account, the same library real wallets follow, so a
   passing result says something about the server rather than about a hand-rolled
   signer that might disagree with it.
   Proves the three outcomes a real player can hit:
     1. a call on the round the clock is in  -> accepted
     2. a call on a round that has closed    -> refused (round_closed)
     3. a call on a round that has not begun -> refused (round_not_open)
   Run: node probe_clock_live.js */
const { execFileSync } = require("child_process");

const API = "http://127.0.0.1:8787";
const CHAIN = "https://api.squeekchain.com/v1/core";

/* One account per probe, generated by eth_account and reused for both the
   statement and the signature. Taking the address from one account and signing
   with another is what made an earlier version of this probe report a mismatch
   that did not exist. */
const PY = `
import json,sys
from eth_account import Account
from eth_account.messages import encode_defunct
mode = sys.argv[1]
if mode == "new":
    acct = Account.create()
else:
    acct = Account.from_key(sys.argv[2])
msg = sys.argv[3] if len(sys.argv) > 3 else "probe"
sig = Account.sign_message(encode_defunct(text=msg), private_key=acct.key).signature.hex()
if not sig.startswith("0x"): sig = "0x" + sig
print(json.dumps({"address": acct.address, "key": acct.key.hex(), "sig": sig}))
`;

function py(args) {
  return JSON.parse(execFileSync("python3", ["-c", PY, ...args], { encoding: "utf8" }).trim());
}

const statement = (round, choice, addr) =>
  ["squeek-round \u2014 lock my round call", "", `Round: ${round}`, `Call: ${choice}`,
    `Wallet: ${addr}`, `Issued: ${new Date().toISOString()}`, "",
    "Signing proves I am the wallet making this call. No gas, no transfer."].join("\n");

(async () => {
  const core = await (await fetch(CHAIN)).json();
  const cfg = core.configuration || {};
  if (!cfg.genesisTimestamp) {
    console.log("chain /core returned no configuration (upstream is flaky); retry shortly");
    process.exitCode = 2;
    return;
  }
  const G = Number(cfg.genesisTimestamp), D = Number(cfg.roundDuration);
  const now = Math.floor(Date.now() / 1000);
  const live = Math.floor((now - G) / D);
  const endsIn = G + (live + 1) * D - now;
  console.log(`=== clock ===\n  live round ${live}   window ends in ${endsIn}s\n`);

  const submit = async (round, choice, tag) => {
    const acct = py(["new"]);                       // this probe's account
    const msg = statement(round, choice, acct.address);
    const signed = py(["sign", acct.key, msg]);     // same account, same text
    const r = await fetch(`${API}/api/points/submit`, {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({ address: acct.address, round, choice, sig: signed.sig, message: msg }),
    });
    const j = await r.json().catch(() => ({}));
    const note = j.error ? "error=" + j.error : (j.duplicate ? "duplicate" : "recorded");
    console.log(`  ${tag.padEnd(32)} R${String(round).padEnd(5)} http=${r.status}  ok=${j.ok === true}  ${note}`);
    return { status: r.status, body: j };
  };

  const a = await submit(live, "zoomies", "call on the LIVE round");
  const b = await submit(live - 1, "zoomies", "call on a CLOSED round");
  const c = await submit(live + 5, "nap", "call on a FUTURE round");

  const okA = a.status === 200 && a.body.ok === true;
  const okB = b.status === 400 && b.body.error === "round_closed";
  const okC = c.status === 400 && c.body.error === "round_not_open";
  console.log("\n=== verdict ===");
  console.log(`  live round accepted        : ${okA ? "PASS" : "FAIL"}`);
  console.log(`  closed round refused       : ${okB ? "PASS" : "FAIL"}`);
  console.log(`  future round refused       : ${okC ? "PASS" : "FAIL"}`);
  process.exitCode = okA && okB && okC ? 0 : 1;
})();
